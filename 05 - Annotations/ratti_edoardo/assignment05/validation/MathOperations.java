package assignment05.validation;

public class MathOperations {

    public static int add(int a, int b) {
        // Intentionally wrong to test validation!
        return a - b;
    }

    public static int sub(int a, int b) {
        return a - b;
    }

    public static int min(int a, int b) {
        return Math.min(a, b);
    }
}
